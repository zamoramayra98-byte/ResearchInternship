

#!/usr/bin/env python3

from pathlib import Path

import nibabel as nib
import numpy as np
import pandas as pd
from scipy.interpolate import interp1d


# ============================================================
# 1. SETTINGS — MATCH THE BASH PIPELINE
# ============================================================

ICA_TR = 1.5
TARGET_TR = 0.5

ICA_FREQ = 1 / ICA_TR
TARGET_FREQ = 1 / TARGET_TR

NUMBER_COMPONENTS = 30

TASKS = ("simon", "rest", "breathhold")


# ============================================================
# 2. DIRECTORIES — MATCH THE BASH BIND MOUNT
# ============================================================

# Bash:
# OUTPUT_ROOT="/data/Mayra_derivatives/vessels/vessels_melodic"
#
# Host:
# /Neurodata/M3PI/derivatives/Mayra_derivatives/vessels/vessels_melodic
#
# Container:
# /data/Mayra_derivatives/vessels/vessels_melodic

BASE_DIRECTORY = Path(
    "/data/Mayra_derivatives/vessels/vessels_melodic"
)


# The Bash pipeline creates ICA component masks inside each
# task-specific MELODIC directory:
#
# ${melodic_output}/IC_masks_split/IC_mask_*.nii.gz

# ============================================================
# 3. LOAD ICA TIME SERIES
# ============================================================

def load_ica_time_series(melodic_directory):
    """
    Load the ICA time series generated by MELODIC.

    melodic_mix:
        Rows = time points
        Columns = ICA components
    """

    mix_file = melodic_directory / "melodic_mix"

    if not mix_file.is_file():
        raise FileNotFoundError(
            f"ICA time-series file not found: {mix_file}"
        )

    time_series = np.loadtxt(mix_file)

    if time_series.ndim == 1:
        time_series = time_series[:, np.newaxis]

    if time_series.ndim != 2:
        raise ValueError(
            f"Unexpected melodic_mix shape: {time_series.shape}"
        )

    if not np.all(np.isfinite(time_series)):
        raise ValueError(
            f"Non-finite values found in {mix_file}"
        )

    print("Original ICA time-series shape:", time_series.shape)

    return time_series


# ============================================================
# 4. RESAMPLE ICA TIME SERIES TO 0.5-SECOND INTERVALS
# ============================================================

def resample_signal_freqs(
    ts,
    freq1=ICA_FREQ,
    freq2=TARGET_FREQ,
    axis=0
):
    """
    Linearly interpolate ICA time series from a 1.5-second
    interval to a 0.5-second interval.

    No CO2 data are used.
    """

    ts = np.asarray(ts, dtype=float)

    if ts.ndim == 0:
        raise ValueError("Input must be a time series.")

    if freq1 <= 0 or freq2 <= 0:
        raise ValueError(
            "Sampling frequencies must be positive."
        )

    n_original = ts.shape[axis]

    if n_original < 2:
        raise ValueError(
            "At least two time points are required."
        )

    original_times = np.arange(n_original) / freq1

    # Preserve the original start and end times.
    n_target = int(
        round((n_original - 1) * freq2 / freq1)
    ) + 1

    target_times = np.arange(n_target) / freq2

    interpolator = interp1d(
        original_times,
        ts,
        axis=axis,
        kind="linear",
        bounds_error=True
    )

    resampled = interpolator(target_times)

    print("Original frequency:", freq1, "Hz")
    print("Target frequency:", freq2, "Hz")
    print("Original time points:", n_original)
    print("Resampled time points:", resampled.shape[axis])
    print("Original duration:", original_times[-1], "seconds")

    return resampled, target_times


# ============================================================
# 5. INSPECT BASH-GENERATED ICA COMPONENT MASKS
# ============================================================

def inspect_component_masks(subject, melodic_directory):
    """
    Inspect the component masks generated by the Bash pipeline.

    Expected directory:
        melodic_directory/IC_masks_split/

    Expected files:
        IC_mask_0000.nii.gz
        IC_mask_0001.nii.gz
        ...

    Reports component-mask voxel counts and physical volumes.
    Does not calculate vascular density.
    Does not transform masks.
    """

    split_directory = melodic_directory / "IC_masks_split"

    if not split_directory.is_dir():
        print(
            f"WARNING: Component mask directory not found:\n"
            f"{split_directory}"
        )
        return

    masks = sorted(
        split_directory.glob("IC_mask_*.nii.gz")
    )

    if not masks:
        print(
            f"WARNING: No component masks found in:\n"
            f"{split_directory}"
        )
        return

    mask_results = []

    for mask_file in masks:

        print(f"\nInspecting component mask: {mask_file.name}")

        mask_image = nib.load(str(mask_file))

        # Component masks should be 3D.
        if len(mask_image.shape) != 3:
            print(
                f"WARNING: Expected a 3D mask, got "
                f"{mask_image.shape}. Skipping."
            )
            continue

        mask_data = mask_image.get_fdata()
        binary_mask = mask_data > 0

        voxel_count = int(np.count_nonzero(binary_mask))

        voxel_volume = float(
            abs(np.linalg.det(mask_image.affine[:3, :3]))
        )

        mask_volume = voxel_count * voxel_volume

        mask_results.append({
            "subject": subject,
            "mask": mask_file.name,
            "shape": str(mask_image.shape),
            "voxel_count": voxel_count,
            "voxel_volume_mm3": voxel_volume,
            "mask_volume_mm3": mask_volume
        })

        print("Shape:", mask_image.shape)
        print("Nonzero voxels:", voxel_count)
        print("Voxel volume (mm3):", voxel_volume)
        print("Mask volume (mm3):", mask_volume)

    if mask_results:

        output_file = (
            melodic_directory / "component_mask_summary.csv"
        )

        pd.DataFrame(mask_results).to_csv(
            output_file,
            index=False
        )

        print("\nComponent mask summary saved to:", output_file)


# ============================================================
# 6. PROCESS ONE SUBJECT AND TASK
# ============================================================

def process_subject_task(subject, task):

    print("\n" + "=" * 60)
    print(f"Processing subject: {subject} | Task: {task}")
    print("=" * 60)

    # Matches the Bash code:
    #
    # subject_out="${OUTPUT_ROOT}/${subject}"
    # task_out="${subject_out}/${task}"
    # melodic_output="${task_out}/${subject}_${task}30_melodic"

    melodic_directory = (
        BASE_DIRECTORY
        / subject
        / task
        / f"{subject}_{task}{NUMBER_COMPONENTS}_melodic"
    )

    if not melodic_directory.is_dir():
        print(
            "WARNING: MELODIC directory not found:\n"
            f"{melodic_directory}\n"
            "Skipping this subject/task."
        )
        return

    print("MELODIC directory:", melodic_directory)

    # A. Inspect component masks produced by Bash.
    inspect_component_masks(
        subject,
        melodic_directory
    )

    # B. Load the original MELODIC time series.
    try:
        ica_time_series = load_ica_time_series(
            melodic_directory
        )
    except (FileNotFoundError, ValueError) as error:
        print(f"WARNING: Skipping {subject} {task}: {error}")
        return

    # C. Resample the ICA time series.
    resampled_ica, target_times = resample_signal_freqs(
        ica_time_series,
        freq1=ICA_FREQ,
        freq2=TARGET_FREQ,
        axis=0
    )

    # D. Save the resampled time series in the same
    #    MELODIC directory.
    component_names = [
        f"component_{i + 1}"
        for i in range(resampled_ica.shape[1])
    ]

    results = pd.DataFrame(
        resampled_ica,
        columns=component_names
    )

    results.insert(0, "time_seconds", target_times)

    output_file = (
        melodic_directory
        / f"{subject}_{task}_ICA_timeseries_0.5s.csv"
    )

    results.to_csv(output_file, index=False)

    print("Resampled ICA shape:", resampled_ica.shape)
    print("Saved resampled ICA time series:", output_file)


# ============================================================
# 7. MAIN — PROCESS ALL SUBJECTS AND TASKS
# ============================================================

def main():

    if not BASE_DIRECTORY.is_dir():
        raise FileNotFoundError(
            f"MELODIC base directory not found:\n"
            f"{BASE_DIRECTORY}\n\n"
            "Expected Bash OUTPUT_ROOT:\n"
            "/data/Mayra_derivatives/vessels/vessels_melodic\n\n"
            "Check the Apptainer bind mount and host directory."
        )

    subjects = sorted(
        folder.name
        for folder in BASE_DIRECTORY.iterdir()
        if folder.is_dir()
        and folder.name.startswith("sub-")
    )

    if not subjects:
        print("No subject folders found:", BASE_DIRECTORY)
        return

    print("Output root:", BASE_DIRECTORY)
    print("Subjects found:", subjects)
    print("Tasks:", TASKS)
    print("ICA TR:", ICA_TR, "seconds")
    print("Target interval:", TARGET_TR, "seconds")

    for subject in subjects:
        for task in TASKS:
            try:
                process_subject_task(subject, task)
            except Exception as error:
                print(
                    f"ERROR processing {subject}, {task}: {error}"
                )
                continue

    print("\n" + "=" * 60)
    print("PYTHON PROCESSING COMPLETED")
    print("Output root:", BASE_DIRECTORY)
    print("=" * 60)


if __name__ == "__main__":
    main()


