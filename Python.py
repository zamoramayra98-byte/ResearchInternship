#!/usr/bin/env python3

from pathlib import Path

import nibabel as nib
import numpy as np
import pandas as pd

from nibabel.processing import resample_from_to
from scipy.interpolate import interp1d


# ============================================================
# 1. SETTINGS — MATCH THE BASH PIPELINE
# ============================================================

ICA_TR = 1.5
TARGET_TR = 0.5

ICA_FREQ = 1 / ICA_TR
TARGET_FREQ = 1 / TARGET_TR

NUMBER_COMPONENTS = 30

TASKS = ("simon", "rest", "breathhold")


# ============================================================
# 2. DIRECTORIES — MATCH THE BASH BIND MOUNT
# ============================================================

# MELODIC output directory
BASE_DIRECTORY = Path(
    "/data/Mayra_derivatives/vessels/vessels_melodic"
)

# Segmentation directory
SEGMENTATION_ROOT = Path(
    "/data/Mayra_derivatives/vessels/segmentations"
)

# Expected segmentation filename
SEGMENTATION_FILENAME = "segmentation_mask.nii.gz"


# ============================================================
# 3. LOAD ICA TIME SERIES
# ============================================================

def load_ica_time_series(melodic_directory):
    """
    Load ICA time series generated by MELODIC.

    melodic_mix:
        Rows = time points
        Columns = ICA components
    """

    mix_file = melodic_directory / "melodic_mix"

    if not mix_file.is_file():
        raise FileNotFoundError(
            f"ICA time-series file not found: {mix_file}"
        )

    time_series = np.loadtxt(mix_file)

    if time_series.ndim == 1:
        time_series = time_series[:, np.newaxis]

    if time_series.ndim != 2:
        raise ValueError(
            f"Unexpected melodic_mix shape: {time_series.shape}"
        )

    if not np.all(np.isfinite(time_series)):
        raise ValueError(
            f"Non-finite values found in {mix_file}"
        )

    print(
        "Original ICA time-series shape:",
        time_series.shape
    )

    return time_series


# ============================================================
# 4. RESAMPLE ICA TIME SERIES
# ============================================================

def resample_signal_freqs(
    ts,
    freq1=ICA_FREQ,
    freq2=TARGET_FREQ,
    axis=0
):
    """
    Linearly interpolate ICA time series from a 1.5-second
    interval to a 0.5-second interval.

    No CO2 data are used.
    """

    ts = np.asarray(ts, dtype=float)

    if ts.ndim == 0:
        raise ValueError("Input must be a time series.")

    if freq1 <= 0 or freq2 <= 0:
        raise ValueError(
            "Sampling frequencies must be positive."
        )

    n_original = ts.shape[axis]

    if n_original < 2:
        raise ValueError(
            "At least two time points are required."
        )

    original_times = np.arange(n_original) / freq1

    # Preserve original start and end times
    n_target = int(
        round((n_original - 1) * freq2 / freq1)
    ) + 1

    target_times = np.arange(n_target) / freq2

    interpolator = interp1d(
        original_times,
        ts,
        axis=axis,
        kind="linear",
        bounds_error=True
    )

    resampled = interpolator(target_times)

    print("Original frequency:", freq1, "Hz")
    print("Target frequency:", freq2, "Hz")
    print("Original time points:", n_original)
    print(
        "Resampled time points:",
        resampled.shape[axis]
    )
    print(
        "Original duration:",
        original_times[-1],
        "seconds"
    )

    return resampled, target_times


# ============================================================
# 5. CALCULATE ICA MASK DENSITY
# ============================================================

def calculate_mask_density(
    component_mask_file,
    segmentation_file
):
    """
    Calculate spatial overlap between an ICA component mask
    and a segmentation mask.

    Binary mask definition:
        Included voxels = finite voxel values > 0

    Density / segmentation coverage:
        overlap_voxels / segmentation_voxels

    ICA precision:
        overlap_voxels / ICA_mask_voxels

    The ICA mask is resampled to the segmentation grid
    when grids differ.

    The segmentation is not resampled.
    """

    # --------------------------------------------------------
    # A. Load images
    # --------------------------------------------------------

    component_img = nib.load(str(component_mask_file))
    segmentation_img = nib.load(str(segmentation_file))

    if len(component_img.shape) != 3:
        raise ValueError(
            f"ICA mask must be 3D: {component_img.shape}"
        )

    if len(segmentation_img.shape) != 3:
        raise ValueError(
            f"Segmentation must be 3D: "
            f"{segmentation_img.shape}"
        )

    # --------------------------------------------------------
    # B. Load and binarize segmentation
    # --------------------------------------------------------

    segmentation_data = segmentation_img.get_fdata()

    segmentation_mask = (
        np.isfinite(segmentation_data)
        & (segmentation_data > 0)
    )

    segmentation_voxels = int(
        np.count_nonzero(segmentation_mask)
    )

    if segmentation_voxels == 0:
        raise ValueError(
            "Segmentation mask contains no positive voxels."
        )

    # --------------------------------------------------------
    # C. Load and binarize ICA mask
    # --------------------------------------------------------

    component_data = component_img.get_fdata()

    component_mask = (
        np.isfinite(component_data)
        & (component_data > 0)
    )

    # --------------------------------------------------------
    # D. Check voxel-grid compatibility
    # --------------------------------------------------------

    same_grid = (
        component_img.shape == segmentation_img.shape
        and np.allclose(
            component_img.affine,
            segmentation_img.affine,
            rtol=0,
            atol=1e-5
        )
    )

    # --------------------------------------------------------
    # E. Resample ICA mask if necessary
    # --------------------------------------------------------

    if not same_grid:

        print(
            "Resampling ICA mask to segmentation grid:",
            component_mask_file.name
        )

        component_binary_img = nib.Nifti1Image(
            component_mask.astype(np.uint8),
            component_img.affine
        )

        resampled_img = resample_from_to(
            component_binary_img,
            (
                segmentation_img.shape,
                segmentation_img.affine
            ),
            order=0
        )

        component_mask = (
            resampled_img.get_fdata() > 0
        )

    # --------------------------------------------------------
    # F. Count voxels on common grid
    # --------------------------------------------------------

    component_voxels = int(
        np.count_nonzero(component_mask)
    )

    overlap_voxels = int(
        np.count_nonzero(
            component_mask & segmentation_mask
        )
    )

    # --------------------------------------------------------
    # G. Calculate coverage and precision
    # --------------------------------------------------------

    # Fraction of segmentation covered by ICA mask
    density = (
        overlap_voxels / segmentation_voxels
    )

    # Fraction of ICA mask inside segmentation
    ica_precision = (
        overlap_voxels / component_voxels
        if component_voxels > 0
        else np.nan
    )

    # --------------------------------------------------------
    # H. Calculate physical volumes
    # --------------------------------------------------------

    # Both masks are evaluated on segmentation grid
    voxel_volume_mm3 = float(
        abs(
            np.linalg.det(
                segmentation_img.affine[:3, :3]
            )
        )
    )

    segmentation_volume_mm3 = (
        segmentation_voxels * voxel_volume_mm3
    )

    component_volume_mm3 = (
        component_voxels * voxel_volume_mm3
    )

    overlap_volume_mm3 = (
        overlap_voxels * voxel_volume_mm3
    )

    return {
        "ica_mask_voxels": component_voxels,
        "segmentation_voxels": segmentation_voxels,
        "overlap_voxels": overlap_voxels,

        "density": density,
        "density_percent": density * 100,

        "ica_precision": ica_precision,
        "ica_precision_percent": (
            ica_precision * 100
            if np.isfinite(ica_precision)
            else np.nan
        ),

        "voxel_volume_mm3": voxel_volume_mm3,

        "segmentation_volume_mm3":
            segmentation_volume_mm3,

        "ica_volume_on_segmentation_grid_mm3":
            component_volume_mm3,

        "overlap_volume_mm3":
            overlap_volume_mm3
    }


# ============================================================
# 6. INSPECT ICA COMPONENT MASKS AND CALCULATE DENSITY
# ============================================================

def inspect_component_masks(
    subject,
    task,
    melodic_directory,
    segmentation_file
):
    """
    Inspect ICA component masks and calculate density.

    Saves:
        component_mask_summary.csv
    """

    split_directory = (
        melodic_directory / "IC_masks_split"
    )

    if not split_directory.is_dir():
        print(
            "WARNING: Component mask directory not found:",
            split_directory
        )
        return

    if not segmentation_file.is_file():
        print(
            "WARNING: Segmentation file not found:",
            segmentation_file
        )
        return

    masks = sorted(
        split_directory.glob("IC_mask_*.nii.gz")
    )

    if not masks:
        print(
            "WARNING: No component masks found:",
            split_directory
        )
        return

    mask_results = []

    for mask_file in masks:

        print(
            f"\nProcessing component mask: "
            f"{mask_file.name}"
        )

        try:

            mask_image = nib.load(str(mask_file))

            if len(mask_image.shape) != 3:
                print(
                    "WARNING: Expected 3D mask. Skipping:",
                    mask_file.name
                )
                continue

            mask_data = mask_image.get_fdata()

            binary_mask = (
                np.isfinite(mask_data)
                & (mask_data > 0)
            )

            # Original mask voxel count
            voxel_count = int(
                np.count_nonzero(binary_mask)
            )

            # Original mask voxel volume
            original_voxel_volume = float(
                abs(
                    np.linalg.det(
                        mask_image.affine[:3, :3]
                    )
                )
            )

            original_mask_volume = (
                voxel_count * original_voxel_volume
            )

            # Calculate density and overlap
            density_results = calculate_mask_density(
                mask_file,
                segmentation_file
            )

            result = {
                "subject": subject,
                "task": task,
                "mask": mask_file.name,
                "shape": str(mask_image.shape),

                "original_ica_mask_voxels":
                    voxel_count,

                "original_voxel_volume_mm3":
                    original_voxel_volume,

                "original_mask_volume_mm3":
                    original_mask_volume,

                "segmentation_file":
                    segmentation_file.name,

                **density_results
            }

            mask_results.append(result)

            print(
                "Original ICA mask voxels:",
                voxel_count
            )

            print(
                "ICA mask voxels on segmentation grid:",
                density_results["ica_mask_voxels"]
            )

            print(
                "Segmentation voxels:",
                density_results["segmentation_voxels"]
            )

            print(
                "Overlap voxels:",
                density_results["overlap_voxels"]
            )

            print(
                "Segmentation coverage:",
                f'{density_results["density_percent"]:.2f}%'
            )

            print(
                "ICA precision:",
                f'{density_results["ica_precision_percent"]:.2f}%'
            )

        except Exception as error:
            print(
                f"ERROR processing {mask_file.name}: {error}"
            )
            continue

    # --------------------------------------------------------
    # Save summary
    # --------------------------------------------------------

    if mask_results:

        output_file = (
            melodic_directory
            / "component_mask_summary.csv"
        )

        pd.DataFrame(mask_results).to_csv(
            output_file,
            index=False
        )

        print(
            "\nComponent mask density summary saved:",
            output_file
        )

    else:
        print(
            "WARNING: No component mask results to save."
        )


# ============================================================
# 7. PROCESS ONE SUBJECT AND TASK
# ============================================================

def process_subject_task(subject, task):

    print("\n" + "=" * 60)
    print(
        f"Processing subject: {subject} | Task: {task}"
    )
    print("=" * 60)

    # --------------------------------------------------------
    # A. Resolve MELODIC directory
    # --------------------------------------------------------

    melodic_directory = (
        BASE_DIRECTORY
        / subject
        / task
        / f"{subject}_{task}{NUMBER_COMPONENTS}_melodic"
    )

    if not melodic_directory.is_dir():
        print(
            "WARNING: MELODIC directory not found:",
            melodic_directory
        )
        print("Skipping this subject/task.")
        return

    print(
        "MELODIC directory:",
        melodic_directory
    )

    # --------------------------------------------------------
    # B. Resolve subject segmentation
    # --------------------------------------------------------

    segmentation_file = (
        SEGMENTATION_ROOT
        / subject
        / SEGMENTATION_FILENAME
    )

    print(
        "Segmentation file:",
        segmentation_file
    )

    # --------------------------------------------------------
    # C. Inspect component masks and calculate density
    # --------------------------------------------------------

    if segmentation_file.is_file():

        inspect_component_masks(
            subject,
            task,
            melodic_directory,
            segmentation_file
        )

    else:
        print(
            f"WARNING: Segmentation not found for {subject}."
        )
        print(
            "Density calculation skipped for this task."
        )

    # --------------------------------------------------------
    # D. Load original MELODIC time series
    # --------------------------------------------------------

    try:
        ica_time_series = load_ica_time_series(
            melodic_directory
        )

    except (FileNotFoundError, ValueError) as error:
        print(
            f"WARNING: Skipping {subject} {task}: {error}"
        )
        return

    # --------------------------------------------------------
    # E. Resample ICA time series
    # --------------------------------------------------------

    resampled_ica, target_times = (
        resample_signal_freqs(
            ica_time_series,
            freq1=ICA_FREQ,
            freq2=TARGET_FREQ,
            axis=0
        )
    )

    # --------------------------------------------------------
    # F. Save resampled time series
    # --------------------------------------------------------

    component_names = [
        f"component_{i + 1}"
        for i in range(resampled_ica.shape[1])
    ]

    results = pd.DataFrame(
        resampled_ica,
        columns=component_names
    )

    results.insert(
        0,
        "time_seconds",
        target_times
    )

    output_file = (
        melodic_directory
        / f"{subject}_{task}_ICA_timeseries_0.5s.csv"
    )

    results.to_csv(
        output_file,
        index=False
    )

    print(
        "Resampled ICA shape:",
        resampled_ica.shape
    )

    print(
        "Saved resampled ICA time series:",
        output_file
    )


# ============================================================
# 8. MAIN — PROCESS ALL SUBJECTS AND TASKS
# ============================================================

def main():

    if not BASE_DIRECTORY.is_dir():
        raise FileNotFoundError(
            f"MELODIC base directory not found:\n"
            f"{BASE_DIRECTORY}\n\n"
            "Expected container directory:\n"
            "/data/Mayra_derivatives/vessels/vessels_melodic"
        )

    if not SEGMENTATION_ROOT.is_dir():
        print(
            "WARNING: Segmentation root does not exist:",
            SEGMENTATION_ROOT
        )
        print(
            "Create the directory and place the real "
            "segmentation masks there."
        )

    subjects = sorted(
        folder.name
        for folder in BASE_DIRECTORY.iterdir()
        if folder.is_dir()
        and folder.name.startswith("sub-")
    )

    if not subjects:
        print(
            "No subject folders found:",
            BASE_DIRECTORY
        )
        return

    print("Output root:", BASE_DIRECTORY)
    print("Segmentation root:", SEGMENTATION_ROOT)
    print("Subjects found:", subjects)
    print("Tasks:", TASKS)
    print("ICA TR:", ICA_TR, "seconds")
    print("Target interval:", TARGET_TR, "seconds")

    for subject in subjects:

        for task in TASKS:

            try:
                process_subject_task(
                    subject,
                    task
                )

            except Exception as error:
                print(
                    f"ERROR processing {subject}, "
                    f"{task}: {error}"
                )
                continue

    print("\n" + "=" * 60)
    print("PYTHON PROCESSING COMPLETED")
    print("Output root:", BASE_DIRECTORY)
    print("=" * 60)


if __name__ == "__main__":
    main()


